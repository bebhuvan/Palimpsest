"""Publishing a year dossier into a release, and proving it again from the release alone.

A year dossier is generated by an explicit command and sits on disk until a build picks it up.
Everything between those two points is where a checked artifact quietly becomes an unchecked one:
a file edited after generation, an index that disagrees with what is beside it, a picture whose
licence nobody looked at because it was looked at months ago.
"""

from __future__ import annotations

import hashlib
import json
import re
from datetime import UTC, datetime
from pathlib import Path

import pytest

from history_pipeline.artifacts import _build_year_artifacts
from history_pipeline.config import LicensePolicy
from history_pipeline.licenses import LicenseRejectedError
from history_pipeline.models import (
    RestatementProvenance,
    RestatementValidation,
    SourceReference,
    YearConnection,
    YearDossier,
    YearDossierSection,
    YearHeadline,
    YearImage,
    YearRegisterEntry,
    YearRelatedYear,
    year_dossier_body,
)
from history_pipeline.verify import _verify_year_contract

SOURCE = SourceReference(
    source_id="wikipedia",
    record_id="34181",
    title="Wikipedia: 1543",
    publisher="Wikimedia Foundation",
    url="https://en.wikipedia.org/wiki/1543",
    license_id="CC-BY-SA-4.0",
    retrieved_at=datetime(2026, 7, 25, tzinfo=UTC),
    citation="“1543”, EN Wikipedia",
)


def image(license_id: str = "PDM-1.0") -> YearImage:
    return YearImage(
        commons_file="File:Portrait.jpg",
        descriptor_url="https://commons.wikimedia.org/wiki/File:Portrait.jpg",
        image_url="https://upload.wikimedia.org/portrait.jpg",
        width=720,
        height=900,
        mime_type="image/jpeg",
        license_id=license_id,
        license_short_name="Public domain",
        attribution="Unknown author — Public domain, via Wikimedia Commons",
        subject_wikidata_id="Q619",
        subject_title="Nicolaus Copernicus",
    )


def dossier(year: int = 1543, picture: YearImage | None = None) -> YearDossier:
    lede = "A book was printed at Nuremberg."
    prose = "A book was printed at Nuremberg in March."
    body = year_dossier_body(None, [], [prose])
    return YearDossier(
        dossier_id=f"year-dossier:{year}:en:{'a' * 16}",
        year=year,
        language="en",
        lede=lede,
        headlines=[YearHeadline(entry_id="chronicle:x", text=lede)],
        sections=[
            YearDossierSection(
                section_id="section:knowledge",
                heading="Science",
                lens="knowledge",
                prose=prose,
                entry_ids=["chronicle:x"],
            )
        ],
        register_entries=[
            YearRegisterEntry(
                entry_id="chronicle:x",
                kind="event",
                text="A book was printed at Nuremberg.",
                image=picture,
            )
        ],
        related_years=[
            YearRelatedYear(
                year=year + 73,
                direction="later",
                connections=[
                    YearConnection(entry_id="chronicle:x", kind="birth", text="Somebody")
                ],
            )
        ],
        chronicle_id=f"chronicle:{year}:en",
        chronicle_revision_id=99,
        evidence_checksum_sha256="b" * 64,
        content_checksum_sha256=hashlib.sha256(body.encode()).hexdigest(),
        source_refs=[SOURCE],
        generation=RestatementProvenance(
            prompt_version="year-dossier-v2",
            prompt_sha256="c" * 64,
            model_identifier="fixture:test",
            source_sha256="b" * 64,
            output_sha256="d" * 64,
            generated_at=datetime(2026, 7, 25, tzinfo=UTC),
        ),
        validation=RestatementValidation(
            policy_version="closed-world-v1", source_chars=100, restatement_chars=len(body)
        ),
    )


def published(tmp_path: Path, *dossiers: YearDossier, policy: LicensePolicy | None = None):
    artifacts = _build_year_artifacts(list(dossiers), tmp_path, license_policy=policy)
    return {artifact.path for artifact in artifacts}


def test_a_year_is_addressed_by_its_year_and_listed_in_one_index(tmp_path: Path) -> None:
    """The key is a small integer the reader already has, because it came from the time slider."""

    paths = published(tmp_path, dossier(1543), dossier(1492))

    assert paths == {"years/1492.json", "years/1543.json", "years/index.json"}
    index = json.loads((tmp_path / "years" / "index.json").read_text())
    assert [entry["year"] for entry in index["years"]] == [1492, 1543]
    # The index carries what a reader needs to tell a live door from a dead one without
    # fetching forty-four dossiers to find out.
    assert index["years"][0]["related_years"] == [1565]
    _verify_year_contract(tmp_path, "years/index.json", paths)


def test_a_release_carrying_no_years_publishes_nothing_rather_than_an_empty_index(
    tmp_path: Path,
) -> None:
    """A release without year pages is complete, not degraded."""

    assert published(tmp_path) == set()
    assert not (tmp_path / "years").exists()


def test_a_picture_the_release_policy_forbids_stops_the_build(tmp_path: Path) -> None:
    """Cleared once when fetched is not cleared: the release is the thing that redistributes it."""

    policy = LicensePolicy(mode="commercial", allowed=["CC0-1.0"], denied=[])

    with pytest.raises(LicenseRejectedError, match=re.escape("PDM-1.0")):
        published(tmp_path, dossier(1543, image()), policy=policy)


def test_a_year_file_edited_after_the_build_fails_verification(tmp_path: Path) -> None:
    paths = published(tmp_path, dossier(1543))
    target = tmp_path / "years" / "1543.json"
    payload = json.loads(target.read_text())
    payload["sections"][0]["prose"] = "A book was printed at Kyoto in March."
    target.write_text(json.dumps(payload))

    with pytest.raises(ValueError, match="checksum does not match"):
        _verify_year_contract(tmp_path, "years/index.json", paths)


def test_an_index_that_disagrees_with_what_is_beside_it_fails(tmp_path: Path) -> None:
    paths = published(tmp_path, dossier(1543), dossier(1492))

    with pytest.raises(ValueError, match="exactly the year files"):
        _verify_year_contract(tmp_path, "years/index.json", paths - {"years/1492.json"})


def test_a_picture_under_an_unrecognised_licence_never_reaches_a_reader(tmp_path: Path) -> None:
    """A file whose licence nothing recognises never came through the Commons gate."""

    paths = published(tmp_path, dossier(1543, image()))
    target = tmp_path / "years" / "1543.json"
    payload = json.loads(target.read_text())
    payload["register_entries"][0]["image"]["license_id"] = "LicenseRef-Proprietary"
    target.write_text(json.dumps(payload))

    with pytest.raises(ValueError, match="unrecognised licence"):
        _verify_year_contract(tmp_path, "years/index.json", paths)


def test_the_reader_disclosure_has_to_survive_into_the_artifact(tmp_path: Path) -> None:
    """A reader is told the prose is machine-written and the lede is not."""

    paths = published(tmp_path, dossier(1543))
    target = tmp_path / "years" / "1543.json"
    payload = json.loads(target.read_text())
    payload["editorial_state"] = "machine_generated"
    payload["lede_kind"] = "assembled"
    target.write_text(json.dumps(payload))

    _verify_year_contract(tmp_path, "years/index.json", paths)
